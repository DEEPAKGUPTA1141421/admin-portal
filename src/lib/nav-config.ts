export function findGroupByPath(pathname: string): { group: NavGroup; leaf: NavLeaf } | null {
  for (const g of NAV) {
    for (const item of g.items) {
      if (pathname === item.href || pathname.startsWith(item.href + "/")) {
        return { group: g, leaf: item };
      }
    }
  }
  return null;
}
