export interface NavGroup {
  title: string;
  icon: LucideIcon;
  href: string;
  items: NavLeaf[];
}

const slugify = (s: string) =>
  s
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

function group(title: string, icon: LucideIcon, base: string, leaves: string[]): NavGroup {
  return {
    title,
    icon,
    href: `/${base}/${slugify(leaves[0])}`,
    items: leaves.map((l) => ({ title: l, href: `/${base}/${slugify(l)}` })),
  };
}

